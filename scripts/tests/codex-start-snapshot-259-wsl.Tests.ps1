# Pester 3.4, Windows PowerShell 5.1 / PowerShell 7. No installer or real Codex.
# #259 WSL loader tests, split from codex-start-snapshot-259.Tests.ps1 (file-size limit).
$ErrorActionPreference = 'Stop'
$bash259 = Join-Path $env:ProgramFiles 'Git\bin\bash.exe'
$noBash259 = -not (Test-Path -LiteralPath $bash259)
# Real WSL: run the same driver in the Ubuntu distro when it is installed.
$wsl259 = Join-Path $env:SystemRoot 'System32\wsl.exe'
$noWsl259 = $true
if (Test-Path -LiteralPath $wsl259) {
    try { $null = & $wsl259 -d Ubuntu --exec true 2>$null; $noWsl259 = $LASTEXITCODE -ne 0 } catch { $noWsl259 = $true }
}

# Round 3/4 (#259 review): the WSL loader generated by scripts/synapse-install.sh is SOURCED into
# the user's shell. Run the real install_synapse_token_loader (extracted from install.sh, never
# the installer itself) with quoted paths, source the result twice and call codex() against a
# stub codex binary: in Git Bash and in the real Ubuntu WSL distro (temp HOME under TestDrive;
# the real ~/.codex is never touched).
Describe 'Generated WSL mcp-env.sh codex() start snapshots #259' {
    BeforeAll {
        $install = Join-Path (Split-Path -Parent $PSScriptRoot) 'synapse-install.sh'
        $text = [IO.File]::ReadAllText($install)
        $from = $text.IndexOf("synapse_sq() {`n")
        # Older loaders had no quoting helper; start at the loader itself so a revert fails on assertions.
        if ($from -lt 0) { $from = $text.IndexOf("install_synapse_token_loader() {`n") }
        $marker = "die `"SYNAPSE_BEARER_TOKEN did not load from `$TOKEN_WSL.`"`n}`n"
        $to = $text.IndexOf($marker)
        if ($from -lt 0 -or $to -lt $from) { throw 'install_synapse_token_loader not found in synapse-install.sh' }
        $script:wslFuncs259 = $text.Substring($from, $to + $marker.Length - $from)
        $script:wslDriver259 = @'
set -u
die() { printf 'DIE %s\n' "$*" >&2; exit 99; }
case "$ROOT_WIN" in
  /*) ROOT="$ROOT_WIN" ;;
  *) ROOT=$(cygpath -u "$ROOT_WIN") ;;
esac
export HOME="$ROOT/home o'neil"
TOKEN_WSL="$ROOT/tok dir/token.txt"
SURFACE_WSL="$ROOT/surf 'x' \$y/codex-tool-surface.json"
SNAPSHOT_RETENTION_HOURS=168
SNAPSHOT_GRACE_MINUTES=10
mkdir -p "$HOME" "$(dirname "$TOKEN_WSL")" "$(dirname "$SURFACE_WSL")" "$ROOT/bin dir"
printf 'synthetic-token-259' > "$TOKEN_WSL"
printf '{\n  "tool_surface_sha256": "%s",\n  "tool_count": 42\n}\n' "$(printf 'a%.0s' $(seq 64))" > "$SURFACE_WSL"
cat > "$ROOT/bin dir/codex" <<'FAKE'
#!/bin/sh
{
  printf 'arg1=%s\n' "${1-}"
  printf 'snap=%s\n' "${SYNAPSE_TOOL_SURFACE_SNAPSHOT_AT_CODEX_START-}"
  printf 'hash=%s\n' "${SYNAPSE_TOOL_SURFACE_HASH_AT_CODEX_START-}"
  if [ -f "${SYNAPSE_TOOL_SURFACE_SNAPSHOT_AT_CODEX_START-/nonexistent}" ]; then echo exists=1; else echo exists=0; fi
} > "$FAKE_REPORT"
exit "${FAKE_EXIT:-0}"
FAKE
chmod +x "$ROOT/bin dir/codex"
. "$ROOT/funcs.sh"
install_synapse_token_loader
. "$HOME/.config/synapse/mcp-env.sh"
dir="$HOME/.config/synapse/codex-start-snapshots"
echo "type=$(type -t codex)"
echo "files_after_source=$(ls -A "$dir" 2>/dev/null | wc -l | tr -d ' ')"
echo "trap_exit=$(trap -p EXIT)"
echo "opts_before=$-"
echo "leak_before=${SYNAPSE_TOOL_SURFACE_SNAPSHOT_AT_CODEX_START-unset}"
mkdir -p "$dir"
: > "$dir/codex-tool-surface-o2147483-aa.json"; touch -d '60 minutes ago' "$dir/codex-tool-surface-o2147483-aa.json"
: > "$dir/codex-tool-surface-o2147484-bb.json"
: > "$dir/codex-tool-surface-o$$-cc.json"; touch -d '8 days ago' "$dir/codex-tool-surface-o$$-cc.json"
: > "$dir/codex-tool-surface-123-456.json"; touch -d '9 days ago' "$dir/codex-tool-surface-123-456.json"
: > "$dir/codex-tool-surface-124-457.json"
# Malformed owner fields prove nothing about a PID: kept even when older than the grace.
: > "$dir/codex-tool-surface-o1:2-dd.json"; touch -d '60 minutes ago' "$dir/codex-tool-surface-o1:2-dd.json"
: > "$dir/codex-tool-surface-o12x3-ee.json"; touch -d '60 minutes ago' "$dir/codex-tool-surface-o12x3-ee.json"
PATH="$ROOT/bin dir:$PATH"
FAKE_REPORT="$ROOT/r1.txt" FAKE_EXIT=0 codex 'arg with space'; echo "status1=$?"
FAKE_REPORT="$ROOT/r2.txt" FAKE_EXIT=7 codex; echo "status2=$?"
# A caller under set -e: codex() must still delete its snapshot and hand back 7.
( set -e; FAKE_REPORT="$ROOT/r3.txt" FAKE_EXIT=7 codex; echo "after_fail_reached=1" ); echo "status3=$?"
echo "opts_after=$-"
echo "trap_exit_after=$(trap -p EXIT)"
echo "leak_after=${SYNAPSE_TOOL_SURFACE_SNAPSHOT_AT_CODEX_START-unset}"
for k in o2147483-aa o2147484-bb o$$-cc 123-456 124-457 o1:2-dd o12x3-ee; do
  n="seed_$(printf '%s' "${k%%-*}" | tr -c 'A-Za-z0-9\n' '_')"
  if [ -e "$dir/codex-tool-surface-$k.json" ]; then echo "$n=1"; else echo "$n=0"; fi
done
sed 's/^/r1_/' "$ROOT/r1.txt"; sed 's/^/r2_/' "$ROOT/r2.txt"; sed 's/^/r3_/' "$ROOT/r3.txt"
for r in r1 r2 r3; do s=$(sed -n 's/^snap=//p' "$ROOT/$r.txt"); if [ -n "$s" ] && [ -e "$s" ]; then echo "${r}_after=1"; else echo "${r}_after=0"; fi; done
echo "remaining=$(ls -A "$dir" | wc -l | tr -d ' ')"
echo "shellpid=$$"
echo "uname=$(uname -s)"
'@

        function Test-WslLoader259([string]$Runner) {
            $root = Join-Path $TestDrive ('wsl ' + [guid]::NewGuid().ToString('N'))
            [void][IO.Directory]::CreateDirectory($root)
            [IO.File]::WriteAllText((Join-Path $root 'funcs.sh'), $script:wslFuncs259)
            [IO.File]::WriteAllText((Join-Path $root 'driver.sh'), ($script:wslDriver259 -replace "`r?`n", "`n"))
            $psi = New-Object Diagnostics.ProcessStartInfo
            if ($Runner -eq 'wsl') {
                # WSLENV /p hands ROOT_WIN to Linux as a /mnt/... path; bash reads the driver from it.
                $psi.FileName = $wsl259
                $psi.Arguments = '-d Ubuntu --exec bash -c "exec bash \"$ROOT_WIN/driver.sh\""'
                $psi.EnvironmentVariables['WSLENV'] = 'ROOT_WIN/p'
            } else {
                $psi.FileName = $bash259
                $psi.Arguments = '"' + ((Join-Path $root 'driver.sh') -replace '\\', '/') + '"'
            }
            $psi.UseShellExecute = $false; $psi.CreateNoWindow = $true
            $psi.RedirectStandardOutput = $true; $psi.RedirectStandardError = $true
            $psi.EnvironmentVariables['ROOT_WIN'] = $root
            foreach ($key in @('SYNAPSE_BEARER_TOKEN', 'SYNAPSE_TOOL_SURFACE_SNAPSHOT_AT_CODEX_START',
                'SYNAPSE_TOOL_SURFACE_HASH_AT_CODEX_START', 'SYNAPSE_TOOL_SURFACE_TOOL_COUNT_AT_CODEX_START')) {
                $psi.EnvironmentVariables.Remove($key)
            }
            $p = [Diagnostics.Process]::Start($psi)
            $out = $p.StandardOutput.ReadToEnd(); $err = $p.StandardError.ReadToEnd()
            if (-not $p.WaitForExit(120000)) { $p.Kill(); throw 'WSL driver timeout' }
            $kv = @{}
            foreach ($line in ($out -split "`r?`n")) { if ($line -match '^([A-Za-z0-9_]+)=(.*)$') { $kv[$Matches[1]] = $Matches[2] } }
            Write-Host ('#259 ' + $Runner + ': exit=' + $p.ExitCode + ' uname=' + $kv.uname + ' stderr=' + $err.Trim())
            $p.ExitCode | Should Be 0
            if ($Runner -eq 'wsl') { $kv.uname | Should Be 'Linux' }
            # Sourced twice: only a function definition, no files, no trap, no exported snapshot vars.
            $kv.type | Should Be 'function'
            $kv.files_after_source | Should Be '0'
            $kv.trap_exit | Should Be ''
            $kv.leak_before | Should Be 'unset'
            # codex() keeps codex's status, deletes its own snapshot and leaks nothing into the shell.
            $kv.status1 | Should Be '0'
            $kv.status2 | Should Be '7'
            $kv.r1_arg1 | Should Be 'arg with space'
            (@($kv.r1_exists, $kv.r2_exists, $kv.r3_exists) -join ',') | Should Be '1,1,1'
            $kv.r1_hash | Should Be ('a' * 64)
            $kv.r1_snap | Should Match ("/codex-tool-surface-o" + $kv.shellpid + "-[0-9a-f]+\.json$")
            $kv.r1_snap | Should Not Be $kv.r2_snap
            (@($kv.r1_after, $kv.r2_after, $kv.r3_after) -join ',') | Should Be '0,0,0'
            # set -e caller: the subshell stops at the failing call with 7; the file is still gone.
            $kv.status3 | Should Be '7'
            $kv.ContainsKey('after_fail_reached') | Should Be $false
            # The caller's own shell options and traps are unchanged.
            $kv.opts_after | Should Be $kv.opts_before
            $kv.trap_exit_after | Should Be ''
            $kv.leak_after | Should Be 'unset'
            # Proof-only prune: dead-old o and old legacy go; fresh dead, live, fresh legacy and
            # malformed owners stay.
            $seeds = @('seed_o2147483', 'seed_o2147484', ('seed_o' + $kv.shellpid), 'seed_123', 'seed_124', 'seed_o1_2', 'seed_o12x3')
            (($seeds | ForEach-Object { $kv[$_] }) -join ',') | Should Be '0,1,1,0,1,1,1'
            $kv.remaining | Should Be '5'
        }
    }

    It 'must_pass_wsl_codex_function_owns_its_snapshot_keeps_status_and_quotes_paths (Git Bash)' -Skip:$noBash259 {
        Test-WslLoader259 'gitbash'
    }

    It 'must_pass_wsl_codex_function_owns_its_snapshot_keeps_status_and_quotes_paths (real WSL Ubuntu)' -Skip:$noWsl259 {
        Test-WslLoader259 'wsl'
    }
}
